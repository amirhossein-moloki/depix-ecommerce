import { MedusaRequest, MedusaResponse } from "@medusajs/framework/http"
import { ContainerRegistrationKeys, MedusaError, Modules } from "@medusajs/framework/utils"
import {
  normalizePhoneNumber,
  SmsNotificationService,
} from "@medusajs/notification-sms"
import { SendOtpRequestType } from "../validators"

// In-memory fallback OTP storage if cache module service is not configured
export const memoryOtpStore = new Map<string, { code: string; expiresAt: number }>()

export const isSkipOtpEnabled = (): boolean => {
  const val = (process.env.SKIP_OTP || process.env.skip_otp || "").toLowerCase().trim()
  return val === "true" || val === "1"
}

export const POST = async (
  req: MedusaRequest<SendOtpRequestType>,
  res: MedusaResponse
) => {
  const { phone } = req.validatedBody || (req.body as any)

  if (!phone) {
    throw new MedusaError(
      MedusaError.Types.INVALID_DATA,
      "Phone number is required"
    )
  }

  const normalizedPhone = normalizePhoneNumber(phone)
  if (!normalizedPhone) {
    throw new MedusaError(
      MedusaError.Types.INVALID_DATA,
      `Invalid phone number format: ${phone}`
    )
  }

  const skipOtp = isSkipOtpEnabled()

  // Generate 5-digit OTP code (use fixed '00000' in dev when SKIP_OTP is enabled)
  const code = skipOtp
    ? "00000"
    : Math.floor(10000 + Math.random() * 90000).toString()
  const ttlSeconds = 300 // 5 minutes
  const cacheKey = `otp:phone:${normalizedPhone}`

  // Try saving to Medusa Cache module service, fallback to memoryOtpStore
  try {
    const cacheService = req.scope.resolve<any>(Modules.CACHE)
    if (cacheService && typeof cacheService.set === "function") {
      await cacheService.set(cacheKey, { code }, ttlSeconds)
    } else {
      memoryOtpStore.set(cacheKey, {
        code,
        expiresAt: Date.now() + ttlSeconds * 1000,
      })
    }
  } catch {
    memoryOtpStore.set(cacheKey, {
      code,
      expiresAt: Date.now() + ttlSeconds * 1000,
    })
  }

  // Send OTP via SMS Notification Service unless skipOtp is enabled
  let logger: any
  try {
    logger = req.scope.resolve(ContainerRegistrationKeys.LOGGER)
  } catch {
    logger = console
  }

  if (skipOtp) {
    logger.info?.(`[DEV] SKIP_OTP is enabled. Generated bypass OTP code '00000' for ${normalizedPhone}. SMS sending bypassed.`)
  } else {
    const smsService = new SmsNotificationService({ logger })
    await smsService.send({
      channel: "sms",
      template: "otp-verification",
      to: normalizedPhone,
      content: {
        text: `کد تایید ورود به سایت: ${code}`,
      },
    })
  }

  res.status(200).json({
    success: true,
    phone: normalizedPhone,
    message: skipOtp
      ? "Dev mode: SKIP_OTP enabled, use '00000' to login"
      : "OTP code sent successfully via SMS",
  })
}
